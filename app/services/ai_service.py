async def analyze_dispute(dispute_text: str) -> Dict[str, Any]:
    validate_input(dispute_text)
    dispute_text = sanitize_input(dispute_text)
    manager = get_llm_manager()

    system_prompt = (
        'You are a senior legal analyst specializing in Indian law with 20+ years of experience. '
        'Provide comprehensive, precise legal analysis and return ONLY valid JSON with required fields.'
    )
    human_prompt = (
        'Please conduct a comprehensive legal analysis of the following dispute:\n\n'
        + dispute_text + '\n\n'
        'Return JSON with fields: case_classification, legal_domain, primary_issue, legal_summary, probable_remedy, '
        'suggested_lawyer_type, recommended_lawyers, lawyer_request_summary, urgency, portal_recommendation, '
        'legal_risk_assessment, preliminary_legal_opinion'
    )
    raw = await invoke_json_llm(manager.primary, system_prompt, human_prompt)

    # Normalize response to match Pydantic model expectations
    out: Dict[str, Any] = {}
    if not isinstance(raw, dict):
        raise ValueError("LLM returned non-dict response for dispute analysis")

    # Basic string fields
    for k in [
        'case_classification', 'legal_domain', 'primary_issue', 'legal_summary',
        'suggested_lawyer_type', 'lawyer_request_summary', 'urgency', 'portal_recommendation',
        'legal_risk_assessment', 'preliminary_legal_opinion'
    ]:
        out[k] = raw.get(k, '')

    # probable_remedy should be a list
    pr = raw.get('probable_remedy', [])
    if isinstance(pr, str):
        # split on common separators into short items
        items = [s.strip() for s in pr.replace('\n', '. ').split('.') if s.strip()]
        out['probable_remedy'] = items
    elif isinstance(pr, list):
        out['probable_remedy'] = pr
    else:
        out['probable_remedy'] = [str(pr)]

    # recommended_lawyers: ensure list of objects with required fields
    recs = raw.get('recommended_lawyers', [])
    normalized = []
    if isinstance(recs, list):
        for r in recs:
            if isinstance(r, dict):
                name = r.get('name') or r.get('full_name') or r.get('lawyer_name') or ''
                specialization = r.get('specialization') or r.get('area') or ''
                exp = r.get('experience_years') or r.get('experience') or r.get('years') or ''
                # Try to extract numeric years if possible
                try:
                    if isinstance(exp, str) and '+' in exp:
                        exp_num = int(''.join(ch for ch in exp if ch.isdigit()))
                    else:
                        exp_num = int(exp)
                except Exception:
                    exp_num = 0
                success_rate = r.get('success_rate', r.get('win_rate', 'N/A'))
                location = r.get('location', '')
                profile_id = r.get('profile_id', r.get('id', ''))
                contact_option = r.get('contact_option', r.get('contact', ''))
                normalized.append({
                    'name': name,
                    'specialization': specialization,
                    'experience_years': exp_num,
                    'success_rate': success_rate,
                    'location': location,
                    'profile_id': profile_id,
                    'contact_option': contact_option,
                })
            else:
                # if it's a string, place it into a minimal object
                normalized.append({
                    'name': str(r), 'specialization': '', 'experience_years': 0,
                    'success_rate': 'N/A', 'location': '', 'profile_id': '', 'contact_option': ''
                })
    else:
        # not a list
        normalized.append({
            'name': str(recs), 'specialization': '', 'experience_years': 0,
            'success_rate': 'N/A', 'location': '', 'profile_id': '', 'contact_option': ''
        })

    out['recommended_lawyers'] = normalized

    return out


