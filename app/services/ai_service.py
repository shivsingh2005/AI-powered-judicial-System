"""
AI service that uses Groq via langchain_groq for all legal analysis.

This service requires a valid GROQ_API_KEY in environment variables.
All responses are generated by LLM, with no mock data fallback.
Provides concise async wrappers that return JSON or text as required by routes.
"""

import os
import json
import asyncio
import traceback
from typing import Any, Dict, List
from dotenv import load_dotenv

from langchain_groq import ChatGroq
from langchain_core.messages import HumanMessage, SystemMessage

# Load env files
load_dotenv('.env.local', override=True)
load_dotenv('.env', override=False)

MODEL_PRIMARY = "llama-3.1-8b-instant"
MODEL_SECONDARY = MODEL_PRIMARY
MAX_INPUT_LENGTH = 6000
DEFAULT_MAX_TOKENS = 2048


def sanitize_input(text: str) -> str:
    if not isinstance(text, str):
        return ""
    return text.replace("```", "").strip()


def validate_input(text: str):
    if not text or not isinstance(text, str):
        raise ValueError("Input cannot be empty.")
    if len(text) > MAX_INPUT_LENGTH:
        raise ValueError("Input exceeds allowed length.")


def extract_json(text: str) -> Any:
    """Try to extract JSON object or array from response text.
    Prefer parsing whole text; fall back to finding first { or [ and last } or ].
    """
    if not isinstance(text, str):
        raise ValueError("Invalid response type")
    txt = text.strip()
    # direct parse
    try:
        return json.loads(txt)
    except Exception:
        pass
    # fallback: find first { or [ and locate its matching closing bracket
    start = None
    for i, ch in enumerate(txt):
        if ch == '{' or ch == '[':
            start = i
            open_ch = ch
            break
    if start is None:
        raise ValueError('No JSON found in response')

    # Find matching closing bracket using a simple stack while respecting string literals
    stack = []
    in_string = False
    escape = False
    opening = '{' if open_ch == '{' else '['
    closing = '}' if opening == '{' else ']'
    for j in range(start, len(txt)):
        ch = txt[j]
        if in_string:
            if escape:
                escape = False
            elif ch == '\\':
                escape = True
            elif ch == '"':
                in_string = False
            continue
        else:
            if ch == '"':
                in_string = True
                continue
            if ch == opening:
                stack.append(ch)
            elif ch == closing:
                if not stack:
                    # unmatched closer; keep going
                    continue
                stack.pop()
                if not stack:
                    end = j
                    snippet = txt[start:end+1]
                    try:
                        return json.loads(snippet)
                    except Exception:
                        # continue searching in case of nested issues
                        break

    # As a last resort, try to locate any {...} or [...] block by rfind as before
    if open_ch == '{':
        end = txt.rfind('}')
    else:
        end = txt.rfind(']')
    if end == -1 or end <= start:
        raise ValueError('Incomplete JSON in response')
    snippet = txt[start:end+1]
    return json.loads(snippet)


async def safe_invoke(llm: ChatGroq, messages: List, retries: int = 3):
    last_exc = None
    for attempt in range(retries):
        try:
            return await llm.ainvoke(messages)
        except Exception as e:
            last_exc = e
            txt = str(e).lower()
            if 'decommission' in txt or 'model_decommissioned' in txt:
                raise
            if attempt == retries - 1:
                raise
            await asyncio.sleep(2 ** attempt)
    if last_exc:
        raise last_exc


class LLMManager:
    def __init__(self):
        api_key = os.getenv('GROQ_API_KEY', '').strip()
        if not api_key or api_key.startswith('gsk_your'):
            raise ValueError('GROQ_API_KEY environment variable is required but not set or invalid.')
        try:
            self.primary = ChatGroq(groq_api_key=api_key, model_name=MODEL_PRIMARY, temperature=0.3, max_tokens=DEFAULT_MAX_TOKENS)
            self.secondary = ChatGroq(groq_api_key=api_key, model_name=MODEL_SECONDARY, temperature=0.3, max_tokens=DEFAULT_MAX_TOKENS)
        except Exception as e:
            traceback.print_exc()
            raise ValueError(f'Failed to initialize LLM clients: {e}')


_MANAGER: LLMManager | None = None


def get_llm_manager() -> LLMManager:
    global _MANAGER
    if _MANAGER is None:
        _MANAGER = LLMManager()
    return _MANAGER


async def invoke_json_llm(llm: ChatGroq, system_prompt: str, human_prompt: str) -> Any:
    """Invoke the LLM and parse JSON from its response. Raises on failure."""
    if llm is None:
        raise ValueError('LLM client not initialized')
    messages = [SystemMessage(content=system_prompt), HumanMessage(content=human_prompt)]
    try:
        resp = await safe_invoke(llm, messages)
        # extract content
        if hasattr(resp, 'content'):
            content = resp.content
        elif hasattr(resp, 'text'):
            content = resp.text
        else:
            content = str(resp)
        return extract_json(content)
    except Exception as e:
        msg = str(e).lower()
        # try secondary once for model decommission errors
        try:
            if 'decommission' in msg or 'model_not_found' in msg:
                manager = get_llm_manager()
                if hasattr(manager, 'secondary') and manager.secondary is not None and llm is not manager.secondary:
                    resp = await safe_invoke(manager.secondary, messages)
                    if hasattr(resp, 'content'):
                        content = resp.content
                    elif hasattr(resp, 'text'):
                        content = resp.text
                    else:
                        content = str(resp)
                    return extract_json(content)
        except Exception:
            traceback.print_exc()
        traceback.print_exc()
        raise


